USE ROLE ACCOUNTADMIN;

-- Create a dedicated role for the ingestion application
CREATE ROLE IF NOT EXISTS LOG_INGESTION_ROLE;

-- Create the application service user
CREATE USER IF NOT EXISTS AJI_LOG_PUSHER_SNOWFLAKE_USER
    TYPE = SERVICE
    DEFAULT_ROLE = LOG_INGESTION_ROLE
    COMMENT = 'Service user for LogPulse Snowpipe Streaming ingestion';

-- Assign the role to the service user
GRANT ROLE LOG_INGESTION_ROLE
    TO USER AJI_LOG_PUSHER_SNOWFLAKE_USER;

ALTER USER AJI_LOG_PUSHER_SNOWFLAKE_USER
SET RSA_PUBLIC_KEY = '<SET_RSA_PUBLIC_KEY>';

DESC USER AJI_LOG_PUSHER_SNOWFLAKE_USER;

USE ROLE ACCOUNTADMIN;

-- 1. Ensure the Database, Schema, and Warehouse exist
CREATE WAREHOUSE IF NOT EXISTS LOG_ANALYTICS_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS LOG_ANALYTICS_DB;
CREATE SCHEMA IF NOT EXISTS LOG_ANALYTICS_DB.BRONZE;

-- 2. Grant Warehouse and Database USAGE to your ingestion role
GRANT USAGE ON WAREHOUSE LOG_ANALYTICS_WH TO ROLE LOG_INGESTION_ROLE;
GRANT USAGE ON DATABASE LOG_ANALYTICS_DB TO ROLE LOG_INGESTION_ROLE;
GRANT USAGE ON SCHEMA LOG_ANALYTICS_DB.BRONZE TO ROLE LOG_INGESTION_ROLE;

-- 3. Grant Table permissions to your ingestion role
GRANT INSERT, SELECT ON TABLE LOG_ANALYTICS_DB.BRONZE.LOG_RECORDS TO ROLE LOG_INGESTION_ROLE;
GRANT INSERT, SELECT ON TABLE LOG_ANALYTICS_DB.BRONZE.INCIDENTS TO ROLE LOG_INGESTION_ROLE;